#!/usr/bin/env python3
"""
Zombie Crop Purge Tool (Cloudinary & Local Softcopy Cache).

Safely identifies and purges derived crop images generated by legacy backend cropping.
Protects all canonical PDFs, original student answer sheets, and full-page renders.
Supports --dry-run (default) and --apply.
"""

import sys
import os
import argparse
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from backend.app.config import settings

def purge_zombie_crops(apply_changes: bool = False):
    print("=" * 65)
    print("   PAPERGRADE AI: ZOMBIE CROP PURGE & STORAGE CLEANUP")
    print("=" * 65)
    print(f"Mode: {'APPLY (Permanent Deletion)' if apply_changes else 'DRY RUN (Preview Only)'}")

    cfg = settings.parsed_cloudinary_config
    cloud_name = cfg.get("cloud_name") or settings.CLOUDINARY_CLOUD_NAME
    print(f"Active Storage Cloud: {cloud_name or 'Local'}\n")

    # 1. Local Disk Crops Cleanup
    local_crop_dir = settings.DATA_DIR / "crops"
    local_deleted = 0
    if local_crop_dir.exists():
        crop_files = list(local_crop_dir.glob("**/*.*"))
        print(f"[Local Storage] Found {len(crop_files)} local cached crop file(s) in {local_crop_dir}")
        for cf in crop_files:
            if cf.is_file():
                if apply_changes:
                    cf.unlink(missing_ok=True)
                local_deleted += 1
        if apply_changes:
            print(f"  -> Deleted {local_deleted} local crop file(s).")
    else:
        print("[Local Storage] No local crop cache directory found.")

    # Also check local cloudinary_cache for renders/*/crops/
    local_cache_renders = settings.DATA_DIR / "cloudinary_cache" / "renders"
    if local_cache_renders.exists():
        local_cache_crops = list(local_cache_renders.glob("**/crops/*.*"))
        if local_cache_crops:
            print(f"[Local Cache] Found {len(local_cache_crops)} cached crop file(s) under cloudinary_cache/renders/")
            for lcf in local_cache_crops:
                if apply_changes:
                    lcf.unlink(missing_ok=True)
            if apply_changes:
                print(f"  -> Deleted {len(local_cache_crops)} local cache crop file(s).")

    # 2. Cloudinary Remote Crops Cleanup
    if cloud_name and settings.STORAGE_BACKEND in ("cloudinary", "auto"):
        try:
            import cloudinary
            import cloudinary.api

            cloudinary.config(
                cloud_name=cloud_name,
                api_key=cfg.get("api_key") or settings.CLOUDINARY_API_KEY,
                api_secret=cfg.get("api_secret") or settings.CLOUDINARY_API_SECRET,
                secure=True
            )

            print("\n[Cloudinary Storage] Scanning for derived crop assets (prefix: 'renders/')...")

            # Scan image resources under renders/
            all_crop_pids = []
            total_bytes = 0
            next_cursor = None

            while True:
                kwargs = {
                    "type": "upload",
                    "prefix": "renders/",
                    "resource_type": "image",
                    "max_results": 500
                }
                if next_cursor:
                    kwargs["next_cursor"] = next_cursor

                res = cloudinary.api.resources(**kwargs)
                resources = res.get("resources", [])

                for r in resources:
                    pub_id = r.get("public_id", "")
                    b = r.get("bytes", 0)

                    # Strictly match crop files inside renders/*/crops/
                    if "/crops/" in pub_id or pub_id.startswith("crops/"):
                        # Hard invariant safety check: Never delete page renders or submissions
                        if "page_" in pub_id or "submissions/" in pub_id or "original_" in pub_id:
                            print(f"  [SAFETY SKIP] {pub_id} matches protected pattern, skipping!")
                            continue

                        all_crop_pids.append(pub_id)
                        total_bytes += b
                        print(f"  {'[DELETE]' if apply_changes else '[PREVIEW]'} {pub_id} ({b / 1024:.1f} KB)")

                next_cursor = res.get("next_cursor")
                if not next_cursor:
                    break

            print(f"\nTotal Zombie Crops Identified: {len(all_crop_pids)} ({total_bytes / 1024:.1f} KB)")

            if apply_changes and all_crop_pids:
                # Delete in chunks of 100 via Cloudinary API
                chunk_size = 100
                total_deleted = 0
                for i in range(0, len(all_crop_pids), chunk_size):
                    chunk = all_crop_pids[i:i + chunk_size]
                    del_res = cloudinary.api.delete_resources(chunk, resource_type="image", invalidate=True)
                    deleted_map = del_res.get("deleted", {})
                    success_count = sum(1 for v in deleted_map.values() if v == "deleted")
                    total_deleted += success_count
                    print(f"  -> Batch {i//chunk_size + 1}: Deleted {success_count} / {len(chunk)} assets.")

                print(f"\nCloudinary Purge Complete! Successfully deleted {total_deleted} zombie crop assets.")
            elif not apply_changes:
                print("\n[DRY RUN COMPLETE] To permanently delete these zombie crops, run with --apply.")

        except Exception as e:
            print(f"[Cloudinary Warning] Could not list/delete Cloudinary crops: {e}")

    print("\nPurge audit completed.")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Purge zombie crop assets from storage.")
    parser.add_argument("--apply", action="store_true", help="Execute deletion (default is dry-run).")
    args = parser.parse_args()
    purge_zombie_crops(apply_changes=args.apply)
